"""Chat tab — "chat with your data" (free-form LLM Q&A over lab values).

Renders the patient chat tab: the LLM receives every non-disabled
measurement of the selected patient within a user-selectable time range
(the same date-range slider as the Trends/Overview tabs; default = the
patient's full range) — measurement date, value, unit, reference range —
plus the patient profile as system-prompt context, then answers free-form
questions with full conversation history.

Conversations are PERSISTED (ChatConversation / ChatMessage tables), not kept
in session state: a page refresh (F5), an app restart, or a tab switch never
loses the transcript, and a patient can keep several conversations (history
list + "new conversation"), like mainstream chat UIs.

The answer itself is generated by a background LlmJob (kind ``chat_answer``,
see llm_jobs._job_chat_answer) instead of blocking the script: the question
is stored the moment it is submitted, the worker keeps running while the user
switches tabs or refreshes the page, and a 2-second polling fragment adopts
the finished answer into a ChatMessage row. An error/abort leaves the question
unanswered and is surfaced as a persistent warning (never silently lost).

Data collection, context formatting, job lookup and answer adoption are plain
functions (no Streamlit) so tests can verify them without a Streamlit runtime.
"""

import json
from datetime import datetime

import streamlit as st

from database import (
    Report, DataPoint, LlmJob, patient_age_years, get_session,
    ChatMessage, collect_report_artifacts,
    create_chat_conversation, get_chat_conversation, list_chat_conversations,
    add_chat_message, get_chat_messages, delete_chat_conversation,
)
from llm_jobs import submit_job
from translations import t
from ui.helpers import _time_range_slider


def collect_chat_measurements(session, patient_id, start_date=None, end_date=None):
    """All non-disabled measurements of a patient within [start_date, end_date].

    The window is the chat tab's date-range slider (default: the patient's
    full range). Unlike the summary prompt (which caps per-biomarker history
    via _collect_historical_data), the chat context deliberately includes
    EVERY non-disabled measurement in the window — the whole point is that
    the model can answer arbitrary questions about any value.

    Returns ``(report_date, canonical_name, value, unit, ref_low, ref_high,
    is_abnormal)`` tuples — the same shape the summary pipeline uses —
    oldest first. Excluded on purpose:
      - disabled values (``is_disabled``, same rule as every chart/analysis),
      - null-valued qualitative entries (``value IS NULL`` — "negativ" etc.
        carry no number the model could reason about),
      - reports without a date (no timestamp to place in the window),
      - anything outside the selected date range.
    """
    query = (
        session.query(DataPoint, Report.report_date)
        .join(Report)
        .filter(
            Report.patient_id == patient_id,
            DataPoint.value.isnot(None),
            DataPoint.is_disabled == False,  # noqa: E712
            Report.report_date.isnot(None),
        )
    )
    if start_date is not None:
        query = query.filter(Report.report_date >= start_date)
    if end_date is not None:
        query = query.filter(Report.report_date <= end_date)
    rows = query.order_by(Report.report_date).all()
    return [
        (rd, dp.canonical_name, dp.value, dp.unit, dp.ref_low, dp.ref_high, dp.is_abnormal)
        for dp, rd in rows
    ]


def collect_chat_artifacts(session, patient_id, start_date=None, end_date=None):
    """Enabled report artifacts of a patient within [start_date, end_date].

    Thin wrapper over the shared ``collect_report_artifacts`` so the chat uses
    exactly the same enable/disable + date-window rules as the summary and risk
    paths. Returns ``(report_date, category, text, source_excerpt, source_page)``
    tuples, oldest first. Excluded: disabled artifacts, and — when a window is
    applied — artifacts on undated reports (no timestamp to place in the range).
    """
    return collect_report_artifacts(session, patient_id, start_date, end_date)


def format_chat_data_context(patient, measurements, lang, range_label="", artifacts=None):
    """Format the patient dataset injected into the chat system prompt.

    Two sections, following the conventions of the summary/interpretation
    prompts:
      - patient profile (age / sex / clinical context — reference ranges are
        age- and sex-dependent, the model needs these to judge values);
      - every measurement grouped per (biomarker, unit), chronological,
        each line ``date: value unit (Ref: low-high) [ABNORMAL]``.
    """
    de = lang == "de"
    parts = []

    # ── Patient profile ─────────────────────────────────────────────────────
    prof_lines = []
    age = patient_age_years(patient)
    if age is not None:
        prof_lines.append(f"{'Alter' if de else 'Age'}: {age}")
    if patient.sex in ("f", "m", "d"):
        sex_labels = {"f": ("weiblich", "female"), "m": ("männlich", "male"), "d": ("divers", "diverse")}
        prof_lines.append(f"{'Geschlecht' if de else 'Sex'}: {sex_labels[patient.sex][0 if de else 1]}")
    if patient.clinical_context:
        prof_lines.append(
            ("Klinischer Kontext (Vorerkrankungen/Medikamente): " if de
             else "Clinical context (conditions/medication): ")
            + str(patient.clinical_context).strip()
        )
    if prof_lines:
        parts.append(("=== PATIENTENPROFIL ===" if de else "=== PATIENT PROFILE ===")
                     + "\n" + "\n".join(prof_lines))

    # ── Measurements grouped per biomarker (chronological) ─────────────────
    groups: dict[tuple[str, str], list] = {}
    for rdate, cname, value, unit, ref_low, ref_high, is_abn in measurements:
        groups.setdefault((cname, unit or ""), []).append(
            (rdate, value, unit, ref_low, ref_high, is_abn)
        )
    blocks = []
    for key in sorted(groups):
        cname, unit = key
        series = sorted(groups[key], key=lambda r: r[0] or datetime.min)
        lines = []
        for rdate, value, u, ref_low, ref_high, is_abn in series:
            date_str = rdate.strftime("%d.%m.%Y") if rdate else "?"
            if ref_low is not None and ref_high is not None:
                ref_str = f" (Ref: {ref_low}-{ref_high} {u or ''})".rstrip()
            elif ref_high is not None:
                ref_str = f" (Ref: < {ref_high} {u or ''})".rstrip()
            elif ref_low is not None:
                ref_str = f" (Ref: > {ref_low} {u or ''})".rstrip()
            else:
                ref_str = ""
            marker = " [ABNORMAL]" if is_abn else ""
            lines.append(f"  - {date_str}: {value} {u or ''}{ref_str}{marker}".rstrip())
        title = f"{cname}{' (' + unit + ')' if unit else ''}"
        blocks.append(f"{title}:\n" + "\n".join(lines))

    span = f" {range_label}" if range_label else ""
    if measurements:
        header = (f"=== MESSWERTE{span} "
                  "(gruppiert nach Biomarker, chronologisch) ===" if de else
                  f"=== MEASUREMENTS{span} "
                  "(grouped per biomarker, chronological) ===")
        parts.append(header + "\n" + "\n".join(blocks))

    # ── Report artifacts (qualitative / narrative findings from the text) ───
    # Enabled artifacts within the chat's date window (disabled ones are
    # excluded upstream). Omitted entirely when there are none, so a patient
    # with only measurements — or only artifacts — still gets a clean context.
    if artifacts:
        art_lines = []
        for rdate, category, text, excerpt, page in artifacts:
            date_str = rdate.strftime("%d.%m.%Y") if rdate else "?"
            line = f"  - {date_str} [{category}]: {text}"
            provenance = []
            if excerpt:
                provenance.append(f'({("Quelle" if de else "Source")}: "{excerpt}")')
            if page:
                provenance.append(f'({("Seite" if de else "page")} {page})')
            if provenance:
                line += " " + " ".join(provenance)
            art_lines.append(line)
        art_header = ("=== QUALITATIVE BEFUNDE UND BERICTNOTIZEN ===" if de else
                      "=== QUALITATIVE FINDINGS AND REPORT NOTES ===")
        parts.append(art_header + "\n" + "\n".join(art_lines))

    return "\n\n".join(parts)


# ── Persistence helpers (plain functions — no Streamlit, unit-testable) ──────

def latest_chat_answer_job(session, conversation_id: int) -> LlmJob | None:
    """Most recent chat_answer job belonging to a conversation (any status).

    The conversation id lives inside ``params_json``, so the recent
    chat_answer jobs are scanned newest-first and matched in Python — cheap
    (a handful of rows) and immune to JSON formatting differences. The scan
    window (50) is generous: a conversation's newest job would only fall out
    of it after 50 questions in OTHER conversations since the last visit.
    """
    jobs = (
        session.query(LlmJob)
        .filter(LlmJob.kind == "chat_answer")
        .order_by(LlmJob.id.desc())
        .limit(50)
        .all()
    )
    for j in jobs:
        try:
            params = json.loads(j.params_json) if j.params_json else {}
        except (json.JSONDecodeError, TypeError):
            continue
        if params.get("conversation_id") == conversation_id:
            return j
    return None


def adopt_chat_answer(session, conversation_id: int, job: LlmJob) -> bool:
    """Persist a finished chat_answer job's result as an assistant message.

    Idempotent via the message's ``job_id`` back-reference: whichever session
    (or poll) sees the finished job first writes the row, later callers no-op.
    Returns True when a message was written.
    """
    if job is None or job.status != "done" or not job.result_text:
        return False
    if any(m.job_id == job.id for m in get_chat_messages(session, conversation_id)):
        return False
    add_chat_message(session, conversation_id, "assistant", job.result_text, job_id=job.id)
    return True


def build_llm_messages(messages) -> list[dict]:
    """Convert ChatMessage rows into the LLM payload, dropping unanswered turns.

    A user row whose answer never arrived (job failed / aborted / interrupted)
    is dropped from the model's view of the conversation — except when it is
    the NEWEST message, which is the question currently being answered. That
    keeps the history coherent (no dangling question the model would try to
    answer again) while the UI still shows the failed turn to the user.
    """
    out = []
    last_i = len(messages) - 1
    for i, m in enumerate(messages):
        if m.role == "user" and i != last_i:
            nxt = messages[i + 1]
            if nxt.role != "assistant":
                continue
        out.append({"role": m.role, "content": m.content})
    return out


def render_chat_tab(session, patient, lang, min_date, max_date, time_range_key):
    """Render the chat tab: time-range slider, conversation picker, transcript,
    and the input line.

    The date-range slider (shared helper with the Trends/Overview tabs, but a
    chat-scoped value key so the chat window stays independent) selects which
    measurements feed the LLM; the default is the patient's full range. The
    transcript is loaded from the DB every run, so it survives reruns, tab
    switches and page refreshes; the selected conversation is a session-state
    preference that falls back to the most recently active one after a refresh.
    The data context is re-collected on every send, so values disabled, reports
    uploaded, or the slider moved since the last question are all reflected.
    """
    st.subheader(t("subheader_chat"))
    st.caption(t("caption_chat"))

    start_date, end_date = _time_range_slider(
        min_date, max_date, time_range_key, f"slider_chat_{patient.id}",
        t("time_range_label"),
    )

    measurements = collect_chat_measurements(session, patient.id, start_date, end_date)
    artifacts = collect_chat_artifacts(session, patient.id, start_date, end_date)
    if not measurements and not artifacts:
        st.info(t("chat_no_data"))
        return

    # Transparency: show exactly what window the LLM is answering from.
    if measurements:
        n_markers = len({(m[1], m[3] or "") for m in measurements})
        st.caption(t(
            "chat_data_context_info",
            n=len(measurements),
            markers=n_markers,
            first=measurements[0][0].strftime("%d.%m.%Y"),
            last=measurements[-1][0].strftime("%d.%m.%Y"),
        ))
    if artifacts:
        st.caption(t("chat_artifacts_context_info", n=len(artifacts)))

    # ── Conversation picker (history list, most recently active first) ─────
    patient_id = patient.id
    conversations = list_chat_conversations(session, patient_id)
    # sel_key is the SINGLE SOURCE OF TRUTH for the active conversation: plain
    # session state, readable/writable from the send path and every callback.
    # widget_key is the selectbox's own key, and the picker is a pure VIEW of
    # sel_key — the body syncs widget_key = sel_key right before rendering
    # (legal: before the widget is instantiated), and the selectbox's on_change
    # writes a manual switch back into sel_key.
    # `conv` is derived from sel_key, NEVER from the selectbox return value: a
    # real browser can hand back a stale widget value (the frontend keeps the
    # previous selection until it repaints), which is exactly the "new
    # conversation looks selected but the question lands in the old one" bug.
    sel_key = f"chat_conv_{patient.id}"
    widget_key = f"chat_conv_widget_{patient.id}"
    conv = None
    if conversations:
        ids = [c.id for c in conversations]
        # After a refresh (F5) the session-state selection is gone → land on
        # the most recently active conversation.
        selected = st.session_state.get(sel_key)
        if selected not in ids:
            selected = ids[0]
            st.session_state[sel_key] = selected

        def _remember_conversation():
            st.session_state[sel_key] = st.session_state[widget_key]

        st.session_state[widget_key] = selected
        st.selectbox(
            t("chat_conversation_label"), ids, index=ids.index(selected),
            format_func=lambda i: next(
                (c.title or t("chat_untitled") for c in conversations if c.id == i), ""),
            key=widget_key, on_change=_remember_conversation,
        )
        conv = get_chat_conversation(session, selected)

    def _start_new_conversation():
        # Callback (runs before the body): only sel_key is touched. The body
        # re-syncs the selectbox to it on the same rerun, so the picker AND the
        # send target both follow the new conversation immediately.
        # Own session: the main run's `session` does not exist yet in a
        # callback, and `patient` is detached from a closed session, so only
        # its already-loaded id is safe to use.
        with get_session() as s:
            # Reuse the current conversation if it is still empty — clicking
            # "New" twice must not litter the history with blank threads.
            current = st.session_state.get(sel_key)
            if current is not None \
                    and get_chat_conversation(s, current) is not None \
                    and not get_chat_messages(s, current):
                return
            new_conv = create_chat_conversation(s, patient_id)
            st.session_state[sel_key] = new_conv.id

    c_new, c_del = st.columns(2)
    c_new.button(t("btn_new_chat"), key=f"chat_new_{patient.id}",
                 on_click=_start_new_conversation)
    if conv is not None and c_del.button(
        t("btn_delete_chat"), key=f"chat_del_{patient.id}_{conv.id}"
    ):
        _confirm_delete_conversation(session, conv, sel_key, widget_key)

    if conv is None:
        # No conversation yet: the transcript is empty and the first question
        # submitted below creates one (titled with that question).
        st.caption(t("chat_no_conversation_hint"))

    messages = get_chat_messages(session, conv.id) if conv else []
    job = latest_chat_answer_job(session, conv.id) if conv else None
    pending = job is not None and job.status in ("pending", "running")

    # Transcript (rendered before the input is processed — st.chat_input
    # renders as a fixed bar at the bottom of the page regardless of script
    # position, so the visual order stays natural).
    for msg in messages:
        with st.chat_message(msg.role):
            st.markdown(msg.content)

    # A question whose answer never arrived (LLM error / abort) stays visible
    # as an unanswered turn — surfaced persistently, across reruns and F5.
    if messages and messages[-1].role == "user" and job is not None \
            and job.status in ("error", "interrupted"):
        st.warning(t("chat_unanswered_note",
                     error=job.error or t(f"job_status_{job.status}")))

    # Live "answer is generating" state + adoption of finished answers. The
    # fragment polls every 2s even while the user sits on another tab (all tab
    # content renders on every rerun, and run_every keeps it alive afterwards),
    # so the answer is adopted into the DB and shown as soon as it lands.
    if conv is not None:
        _chat_answer_poll(conv.id)

    user_msg = st.chat_input(
        t("chat_input_placeholder"), key=f"chat_input_{patient.id}", disabled=pending,
    )
    if user_msg and not pending:
        newly_created = conv is None
        if conv is None:
            conv = create_chat_conversation(session, patient.id, title=user_msg)
            st.session_state[sel_key] = conv.id
        # Persist the question BEFORE submitting the job: the worker may
        # finish while this script run is still going, and the adoption then
        # appends the answer after this row (correct transcript order).
        user_row = add_chat_message(session, conv.id, "user", user_msg)
        range_label = (
            f"{start_date.strftime('%d.%m.%Y')} – {end_date.strftime('%d.%m.%Y')}"
            if start_date and end_date else ""
        )
        context = format_chat_data_context(
            patient, measurements, lang, range_label=range_label, artifacts=artifacts,
        )
        submitted = submit_job(
            "chat_answer", "job_kind_chat_answer",
            params={
                "conversation_id": conv.id,
                "messages": build_llm_messages(get_chat_messages(session, conv.id)),
                "data_context": context,
            },
        )
        if submitted is None:
            # Kind lock lost (another conversation's answer is still running):
            # roll the question back so it doesn't sit there unanswered forever.
            session.delete(user_row)
            session.commit()
            if newly_created and not get_chat_messages(session, conv.id):
                # The conversation only existed to hold this question — undo it.
                delete_chat_conversation(session, conv.id)
                st.session_state.pop(sel_key, None)
            st.info(t("msg_job_already_running"))
        else:
            # st.rerun() raises, so main()'s end-of-run session.close() never
            # runs on this path — release the DB connection here (see
            # ui.helpers._job_button for the same pattern).
            session.close()
            st.rerun()

    st.caption(t("chat_disclaimer"))


@st.fragment(run_every=2)
def _chat_answer_poll(conversation_id: int):
    """Poll this conversation's newest chat_answer job (see render_chat_tab).

    - pending/running → live progress bar (the worker reports chat_thinking);
    - done & not yet adopted → write the assistant ChatMessage row, then an
      app-scoped st.rerun() so the transcript (rendered OUTSIDE this fragment)
      picks the answer up. The active tab is client-side state, so a user who
      switched away stays put — the transcript updates underneath;
    - done & adopted, or error/interrupted → render nothing (the persistent
      unanswered-warning in the tab body covers failures).
    """
    with get_session() as s:
        job = latest_chat_answer_job(s, conversation_id)
        if job is None:
            return
        if job.status in ("pending", "running"):
            st.progress(
                (job.progress_current or 0) / 100.0,
                text=job.progress_message or t("chat_thinking"),
            )
            return
        if adopt_chat_answer(s, conversation_id, job):
            st.rerun()


def _confirm_delete_conversation(session, conv, sel_key: str, widget_key: str):
    """Confirmation dialog for deleting a conversation (destructive → dialog,
    same pattern as report deletion)."""

    @st.dialog(t("dialog_confirm_delete_chat_title"), width="medium")
    def _dialog():
        n = session.query(ChatMessage).filter(
            ChatMessage.conversation_id == conv.id).count()
        st.markdown(t(
            "dialog_confirm_delete_chat_text",
            title=conv.title or t("chat_untitled"), n=n,
        ))
        cols = st.columns(2)
        if cols[0].button(t("btn_confirm_delete"), type="secondary",
                          key="dlg_del_chat_confirm", width="stretch"):
            delete_chat_conversation(session, conv.id)
            # Drop both selection keys: the deleted id must not linger in the
            # selectbox's widget state (it would no longer be a valid option).
            st.session_state.pop(sel_key, None)
            st.session_state.pop(widget_key, None)
            session.close()
            st.rerun()
        cols[1].button(t("btn_cancel"), key="dlg_del_chat_cancel", width="stretch")

    _dialog()
